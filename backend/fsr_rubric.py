def select_branch(material):
    title = material.get('scope_name', '')
    title += ' ' + ' '.join(s.get('filename', '') for s in material.get('sources', []) if s.get('document_category') == 'project_report')
    choices = [
        ('innovation', ['科技创新篇', '创新专项', '科研']),
        ('turbine', ['通流', '汽轮机本体']),
        ('energy', ['空冷岛', '节能', '冷却塔', '节水']),
        ('heat', ['工业抽汽', '供热', '热网', '灵活性']),
        ('safety', ['抗燃油', '主汽门', '轴系', '高旁', '旁路', '抽汽系统优化', '可靠性', '保护', '安全', '疏水']),
    ]
    for key, terms in choices:
        hits = [t for t in terms if t in title]
        if hits:
            return dict(id=key, name=BRANCHES[key][0], reason='报告名称识别：'+'、'.join(hits), source='title')
    return dict(id=None, name='待选择项目分支', reason='报告名称不足以明确项目分支，请选择后重新评审。', source='unresolved')


