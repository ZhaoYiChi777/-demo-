def source_metadata(row):
    metadata = {key: row.get(column, '') for key, column in SOURCE_FIELDS.items()}
    value = metadata['problem_level']
    metadata['severity'] = int(value[0]) if value and value[0] in '0123' else None
    metadata['judgment_kind'] = {0: 'support', 3: 'veto'}.get(metadata['severity'], 'requirement')
    return metadata
